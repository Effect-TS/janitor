/**
 * Regenerates `src/Chat/Sandbox/MulticaSkill.ts` from the `multica-platform`
 * skill folder in multica-ai/multica, at the tag of the CLI the chat sandbox
 * pins. Run through `vp run chat:multica-skill`.
 */
import * as NodeRuntime from "@effect/platform-node/NodeRuntime"
import * as NodeServices from "@effect/platform-node/NodeServices"
import * as Effect from "effect/Effect"
import * as FileSystem from "effect/FileSystem"
import * as FetchHttpClient from "effect/http/FetchHttpClient"
import * as HttpClient from "effect/http/HttpClient"
import * as HttpClientRequest from "effect/http/HttpClientRequest"
import * as HttpClientResponse from "effect/http/HttpClientResponse"
import * as Layer from "effect/Layer"
import * as Schema from "effect/Schema"
import { MULTICA_CLI_VERSION } from "../src/Chat/Sandbox/MulticaCli.ts"

const REPO = "multica-ai/multica"
const FOLDER = "server/internal/service/builtin_skills/multica-platform"
const TAG = `v${MULTICA_CLI_VERSION}`
const OUTPUT = new URL("../src/Chat/Sandbox/MulticaSkill.ts", import.meta.url).pathname

const Entries = Schema.Array(Schema.Struct({ type: Schema.String, path: Schema.String }))

const program = Effect.gen(function* () {
  const client = (yield* HttpClient.HttpClient).pipe(
    HttpClient.mapRequest(HttpClientRequest.setHeader("user-agent", "janitor")),
    HttpClient.filterStatusOk,
  )

  /** Every file under `path` at the tag, depth first. */
  const list = (path: string): Effect.Effect<ReadonlyArray<string>, unknown> =>
    client.get(`https://api.github.com/repos/${REPO}/contents/${path}?ref=${TAG}`).pipe(
      Effect.flatMap(HttpClientResponse.schemaBodyJson(Entries)),
      Effect.flatMap((entries) =>
        Effect.forEach(entries, (entry) =>
          entry.type === "dir"
            ? list(entry.path)
            : Effect.succeed(entry.type === "file" ? [entry.path] : []),
        ),
      ),
      Effect.map((nested) => nested.flat()),
    )

  const paths = [...(yield* list(FOLDER))].sort()
  const files = yield* Effect.forEach(paths, (path) =>
    client.get(`https://raw.githubusercontent.com/${REPO}/${TAG}/${path}`).pipe(
      Effect.flatMap((response) => response.text),
      Effect.map((content) => ({ path: path.slice(FOLDER.length + 1), content })),
    ),
  )

  const fs = yield* FileSystem.FileSystem
  yield* fs.writeFileString(
    OUTPUT,
    `// Generated by \`vp run chat:multica-skill\` from ${REPO}@${TAG}, ${FOLDER}. Do not edit.
import type { SkillFile } from "./Provision.ts"

/** The folder name under \`$HOME/.agents/skills\`. */
export const MULTICA_SKILL_NAME = "multica-platform"

export const MULTICA_SKILL_FILES: ReadonlyArray<SkillFile> = ${yield* Schema.encodeEffect(Schema.fromJsonString(Schema.Unknown, { space: 2 }))(files)}
`,
  )
  yield* Effect.logInfo(`Wrote ${files.length} files from ${REPO}@${TAG}`)
})

program.pipe(
  Effect.provide(Layer.mergeAll(NodeServices.layer, FetchHttpClient.layer)),
  NodeRuntime.runMain,
)
